#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

function findTool(name, candidatePaths = []) {
  // Check candidate paths first
  for (const p of candidatePaths) {
    if (fs.existsSync(p)) {
      try {
        fs.accessSync(p, fs.constants.X_OK);
        return p;
      } catch {}
    }
  }

  // Fall back to which
  try {
    const res = execSync(`which ${name}`, { stdio: ["pipe", "pipe", "ignore"], encoding: "utf-8" }).trim();
    if (res && fs.existsSync(res)) return res;
  } catch {}

  return null;
}

const homeDir = process.env.HOME || "";

const clang = findTool("clang", [
  path.join(homeDir, ".local", "bin", "llvm", "bin", "clang"),
  path.join(homeDir, "local", "bin", "llvm", "bin", "clang"),
  "/opt/homebrew/opt/llvm/bin/clang",
  "/usr/local/opt/llvm/bin/clang",
]);

const wasmOpt = findTool("wasm-opt", [
  path.join(homeDir, ".local", "bin", "binaryen", "bin", "wasm-opt"),
  path.join(homeDir, "local", "bin", "binaryen", "bin", "wasm-opt"),
  "/opt/homebrew/bin/wasm-opt",
  "/usr/local/bin/wasm-opt",
]);

if (!clang) {
  console.error("Error: clang with wasm32 support not found. Please install llvm.");
  process.exit(1);
}

console.log(`Using clang: ${clang}`);
if (wasmOpt) {
  console.log(`Using wasm-opt: ${wasmOpt}`);
} else {
  console.log("wasm-opt not found; skipping binaryen post-optimization step.");
}

// 1. Ensure layouts and C headers are fresh
console.log("Generating layouts and C headers...");
execSync(`node "${path.join(__dirname, "generate_layouts.js")}"`, { stdio: "inherit" });

// 2. Transpile TypeScript core modules to C
console.log("Transpiling TypeScript core modules to freestanding C...");
execSync(`npx vite-node "${path.join(__dirname, "transpiler", "index.ts")}" --all --write`, { stdio: "inherit" });

const cSource = path.join(rootDir, "src", "core", "c", "webdb_core.c");
const distDir = path.join(rootDir, "dist");
const wasmDir = path.join(rootDir, "src", "core", "wasm");

fs.mkdirSync(distDir, { recursive: true });
fs.mkdirSync(wasmDir, { recursive: true });

const rawWasm = path.join(distDir, "webdb_core.raw.wasm");
const outWasm = path.join(distDir, "webdb_core.wasm");
const coreWasm = path.join(wasmDir, "webdb_core.wasm");

// 2. Compile with clang targeting wasm32
console.log("Compiling C core to WebAssembly (wasm32-nostdlib)...");
const compileCmd = [
  `"${clang}"`,
  "--target=wasm32",
  "-nostdlib",
  "-O3",
  "-flto",
  "-Wl,--no-entry",
  "-Wl,--import-memory",
  "-Wl,--export-dynamic",
  "-Wl,--lto-O3",
  `-I "${path.join(rootDir, "src", "core", "c")}"`,
  `-o "${rawWasm}"`,
  `"${cSource}"`,
].join(" ");

execSync(compileCmd, { stdio: "inherit" });

// 3. Optimize with wasm-opt if available
if (wasmOpt) {
  console.log("Optimizing WebAssembly binary with wasm-opt -O3...");
  execSync(`"${wasmOpt}" -O3 --converge "${rawWasm}" -o "${outWasm}"`, { stdio: "inherit" });
  try { fs.unlinkSync(rawWasm); } catch {}
} else {
  fs.copyFileSync(rawWasm, outWasm);
}

// Copy to src/core/wasm for development & testing
fs.copyFileSync(outWasm, coreWasm);

// Generate TypeScript module with embedded wasm bytes for bundler-free execution
const wasmBytes = fs.readFileSync(outWasm);
const wasmBase64 = wasmBytes.toString("base64");
const wasmModuleTs = `/**
 * Embedded WebDB Core WebAssembly binary (Base64 encoded).
 * Auto-generated by scripts/build_wasm.js. Do not edit manually.
 */
export const WEBDB_CORE_WASM_BASE64 = "${wasmBase64}";

let cachedBytes: Uint8Array | null = null;

export function getWebDbCoreWasmBytes(): Uint8Array {
  if (!cachedBytes) {
    const maybeBuffer = (globalThis as unknown as { Buffer?: { from: (b64: string, enc: string) => Uint8Array } }).Buffer;
    if (typeof maybeBuffer !== "undefined" && typeof maybeBuffer.from === "function") {
      cachedBytes = new Uint8Array(maybeBuffer.from(WEBDB_CORE_WASM_BASE64, "base64"));
    } else {
      const binaryString = atob(WEBDB_CORE_WASM_BASE64);
      const len = binaryString.length;
      cachedBytes = new Uint8Array(len);
      for (let i = 0; i < len; i++) {
        cachedBytes[i] = binaryString.charCodeAt(i);
      }
    }
  }
  return cachedBytes;
}
`;
fs.writeFileSync(path.join(wasmDir, "embedded_wasm.ts"), wasmModuleTs);

const stats = fs.statSync(outWasm);
console.log(`\n🎉 WebDB C Core successfully compiled to WASM!`);
console.log(`📦 Output: ${outWasm}`);
console.log(`⚖️  Size: ${(stats.size / 1024).toFixed(2)} KB (${stats.size} bytes)\n`);
